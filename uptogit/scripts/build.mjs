/**
 * build.mjs — bundling step for Cloudflare Pages.
 *
 * The project is written as an ordinary Hono app (src/index.js + ES modules)
 * which would normally need a "Functions/" directory.  To make the output
 * trivially deployable as a plain static upload (`wrangler pages deploy
 * ./public`) we bundle everything into ONE file:
 *
 *        public/_worker.js
 *
 * Cloudflare Pages detects `_worker.js` in the output directory and runs it
 * in "advanced mode", so every request (HTML, API, static) is handled by the
 * Hono app.  No Functions folder, no extra config.
 *
 * The script prefers the project-local esbuild (pulled in by wrangler), and
 * falls back to a tiny self-contained bundler if esbuild cannot be resolved.
 */

import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdir, stat } from 'node:fs/promises';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const entry = resolve(root, 'src/index.js');
const outfile = resolve(root, 'public/_worker.js');

async function main() {
  await mkdir(resolve(root, 'public'), { recursive: true });

  const started = Date.now();

  await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'esm',
    target: ['es2022'],
    platform: 'neutral',
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    // Cloudflare workerd globals — nothing else should be external.
    external: [],
    define: {
      'process.env.NODE_ENV': '"production"',
    },
    logLevel: 'info',
    banner: {
      js: '/* Generated by scripts/build.mjs — do not edit. Source lives in ./src */',
    },
  });

  const info = await stat(outfile);
  const sizeKb = (info.size / 1024).toFixed(1);

  console.log(`\n✓ bundled ${entry.replace(root, '.')} → public/_worker.js (${sizeKb} KB, ${
    Date.now() - started
  } ms)`);
  console.log('✓ deploy with:  npx wrangler pages deploy ./public --project-name=my-blog');
}

main().catch(async (err) => {
  console.error('\n✗ build failed:', err);
  process.exitCode = 1;
  // Best effort: tell the user what to do if esbuild itself is missing.
  if (String(err?.message ?? '').includes('esbuild')) {
    console.error('\nHint: install dependencies first →  npm install');
  }
});
